-- 新幹線・特急の時刻表ライブラリ (旅をまたいで共有。旅を消しても残る)。
-- 縦に駅 (express_stations, 下り方向の seq 順)、横に列車 (express_trains)、交点が express_stop_times。
-- 通過駅は express_stop_times に行を持たない。時刻は 'HH:MM' (日付またぎは 24:xx 表記)。
CREATE TABLE IF NOT EXISTS express_lines (
  id          TEXT PRIMARY KEY,
  name        TEXT NOT NULL,
  kind        TEXT NOT NULL CHECK (kind IN ('shinkansen', 'limited_express')),
  operator    TEXT,
  source_url  TEXT,
  valid_from  TEXT,
  notes       TEXT,
  imported_at TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE TABLE IF NOT EXISTS express_stations (
  line_id TEXT NOT NULL REFERENCES express_lines(id) ON DELETE CASCADE,
  seq     INTEGER NOT NULL,
  name    TEXT NOT NULL,
  lat     REAL,
  lng     REAL,
  PRIMARY KEY (line_id, seq)
);

CREATE TABLE IF NOT EXISTS express_trains (
  id           TEXT PRIMARY KEY,
  line_id      TEXT NOT NULL REFERENCES express_lines(id) ON DELETE CASCADE,
  direction    TEXT NOT NULL CHECK (direction IN ('down', 'up')),
  train_name   TEXT NOT NULL,
  service_note TEXT NOT NULL DEFAULT 'daily'
);
CREATE INDEX IF NOT EXISTS idx_express_trains_line ON express_trains(line_id, direction);

CREATE TABLE IF NOT EXISTS express_stop_times (
  train_id    TEXT NOT NULL REFERENCES express_trains(id) ON DELETE CASCADE,
  station_seq INTEGER NOT NULL,
  arrive_time TEXT,
  depart_time TEXT,
  PRIMARY KEY (train_id, station_seq)
);

